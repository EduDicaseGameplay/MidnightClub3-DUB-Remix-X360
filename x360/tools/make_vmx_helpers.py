"""MC3 X-19 (2026-11-11): writes runtime/cpu/vmx_helpers.cpp, the CRT's __savevmx_N/__restvmx_N (LIBCMT crtvmx.obj)
as functions of our own, with the original instruction words read from a linked image (bre360.pe + its map).
The CRT's are assembly the linker cannot place (LNK4065); ours are COMDATs that order.txt puts in the middle of
.text, so no caller is past the 32 MB reach of bl and the linker makes none of its broken copies.
Each entry point is a function holding its own run of the chain down to the blr."""
import re
import struct
import sys

pe, mapf, out = sys.argv[1], sys.argv[2], sys.argv[3]
d = open(pe, 'rb').read()
e = struct.unpack('<I', d[0x3C:0x40])[0]
nsec = struct.unpack('<H', d[e + 6:e + 8])[0]
opt = struct.unpack('<H', d[e + 20:e + 22])[0]
base = struct.unpack('<I', d[e + 24 + 28:e + 24 + 32])[0]
secs = []
for i in range(nsec):
    o = e + 24 + opt + i * 40
    vsize, va, rsize, raw = struct.unpack('<IIII', d[o + 8:o + 24])
    secs.append((base + va, vsize, raw))


def word(va):
    for sva, vsize, raw in secs:
        if sva <= va < sva + vsize:
            return struct.unpack('>I', d[raw + va - sva:raw + va - sva + 4])[0]
    raise KeyError(hex(va))


syms = {}
for line in open(mapf, encoding='latin-1'):
    m = re.match(r'\s*0003:[0-9a-f]{8}\s+(__(?:save|rest)vmx(?:_\d+)?)\s+([0-9a-f]{8})\s.*crtvmx', line)
    if m:
        syms[m.group(1)] = int(m.group(2), 16)
assert len(syms) == 166, len(syms)
lines = ['// Generated by x360/tools/make_vmx_helpers.py from the CRT (LIBCMT crtvmx.obj) words; see that script.',
         '#include <ppcintrinsics.h>', '', 'extern "C" {', '']
for name in sorted(syms, key=lambda n: (n[:9], int(n.split('_')[-1]) if n[-1].isdigit() else 0)):
    va = syms[name]
    words = []
    while True:
        w = word(va)
        words.append(w)
        va += 4
        if w == 0x4E800020:  # blr
            break
        assert len(words) < 400
    for w in words:  # every vector store/load must be a valid stvx128/lvx128/stvx/lvx form
        if w >> 26 == 4:
            assert (w & 0x7F3) not in (0x303, 0x703), (name, hex(w))
    lines.append('__declspec(naked) void %s() {' % name)
    lines += ['    __emit(0x%08X);' % w for w in words]
    lines += ['}', '']
lines.append('}  // extern "C"')
open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('%d helpers, %d words' % (len(syms), sum(l.count('__emit') for l in lines)))
